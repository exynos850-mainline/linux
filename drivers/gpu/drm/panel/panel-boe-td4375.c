static int td4375_boe_off(struct td4375_boe *ctx)
{
	struct mipi_dsi_multi_context dsi_ctx = { .dsi = ctx->dsi };

	ctx->dsi->mode_flags &= ~MIPI_DSI_MODE_LPM;

	mipi_dsi_dcs_set_display_off_multi(&dsi_ctx);
	mipi_dsi_dcs_enter_sleep_mode_multi(&dsi_ctx);
	mipi_dsi_msleep(&dsi_ctx, 4 * 17); /* vendor: 4 frames at 60fps */

	return dsi_ctx.accum_err;
}

static int td4375_boe_enable(struct drm_panel *panel)
{
	struct td4375_boe *ctx = to_td4375_boe(panel);
	struct device *dev = &ctx->dsi->dev;
	struct mipi_dsi_multi_context dsi_ctx = { .dsi = ctx->dsi };
	int ret;

	ret = td4375_boe_on(ctx);
	if (ret < 0) {
		dev_err(dev, "failed to initialize panel: %d\n", ret);
		return ret;
	}

	mipi_dsi_dcs_set_display_on_multi(&dsi_ctx);
	mipi_dsi_msleep(&dsi_ctx, 20);
	mipi_dsi_dcs_write_seq_multi(&dsi_ctx, MIPI_DCS_WRITE_CONTROL_DISPLAY,
				     0x24);

	return dsi_ctx.accum_err;
}

static int td4375_boe_disable(struct drm_panel *panel)
{
	struct td4375_boe *ctx = to_td4375_boe(panel);
	struct device *dev = &ctx->dsi->dev;
	int ret;

	ret = td4375_boe_off(ctx);
	if (ret < 0)
		dev_err(dev, "failed to turn off panel: %d\n", ret);

	return ret;
}

